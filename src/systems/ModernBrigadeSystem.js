function brigade(side,type){
  const T=TEMPLATES[type]??TEMPLATES.heavy;
  const faction=side==="RED"?"chinese":"japanese";
  const D=DEPLOYMENT[side], arr=[], bdeHQ=`${side}_BDE_HQ`;
  arr.push(make(bdeHQ,`${side==="RED"?"红方":"蓝方"}${T.name}旅指挥所`,faction,"headquarters","brigade",D.hq.q,D.hq.r,320,3,12,3,1,"LOG_VEH",8,T.name,null));
  D.battalions.forEach((P,i)=>{
    const b=i+1, bnHQ=`${side}_BN${b}_HQ`, form=`${T.name}·第${b}合成营`;
    arr.push(make(bnHQ,`第${b}合成营指挥所`,faction,"headquarters","battalion",P.hq.q,P.hq.r,180,3,9,4,1,"LOG_VEH",4,form,bdeHQ));
    arr.push(...maneuverCompanies(T,side,b,faction,P.c,form,bnHQ));
  });
  arr.push(make(`${side}_ART1`,"旅炮兵营第1火力连",faction,"artillery","company",D.art1.q,D.art1.r,120,13,5,4,6,T.art,6,T.name,bdeHQ));
  arr.push(make(`${side}_ART2`,"旅炮兵营第2火力连",faction,"artillery","company",D.art2.q,D.art2.r,120,13,5,4,6,T.art,6,T.name,bdeHQ));
  arr.push(make(`${side}_AD`,"旅防空营野战防空连",faction,"air_defense","company",D.ad.q,D.ad.r,110,7,7,4,4,T.ad,6,T.name,bdeHQ));
  arr.push(make(`${side}_RECON`,"旅侦察营无人侦察连",faction,"recon","company",D.recon.q,D.recon.r,90,4,5,7,4,"UAV_RECON",6,T.name,bdeHQ));
  arr.push(make(`${side}_ENG`,"旅作战支援营工程连",faction,"engineer","company",D.eng.q,D.eng.r,100,5,7,4,1,"ENG_VEH",10,T.name,bdeHQ));
  arr.push(make(`${side}_LOG`,"旅勤务保障营保障连",faction,"supply","company",D.log.q,D.log.r,100,2,6,4,1,"LOG_VEH",18,T.name,bdeHQ));
  return arr;
}

export class ModernBrigadeSystem {
  static isModern(config){return config?.modernBrigadeSelection===true;}
  static getSelection(){try{return JSON.parse(sessionStorage.getItem("modernBrigadeSelection")||"{}");}catch{return {};}}
  static generate(config){
    const s=this.getSelection();
    const units=[...brigade("RED",s.red||"heavy"),...brigade("BLUE",s.blue||"medium")];
    // 最后一层内部自检：任何单位都不得落入预留河道列。
    for(const u of units){
      if(u.q===29||u.q===30) console.error("[现代旅编组] 单位落入河道预留列",u.id,u.q,u.r);
    }
    return units;
  }
  static templateInfo(){return TEMPLATES;}
}
