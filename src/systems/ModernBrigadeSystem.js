const eqName = id => EQUIPMENT[id]?.name ?? id;

function make(id,name,faction,type,echelon,q,r,strength,attack,defense,movement,range,equipment,qty,formation,parentHQ=null){
  return {
    id, name:`${name}｜${eqName(equipment)}`, fullName:name,
    faction,type,echelon,q,r,strength,maxStrength:strength,manpower:strength,maxManpower:strength,
    attack,defense,movement,movementPoints:movement,maxMovementPoints:movement,
    actionPoints:4,maxActionPoints:4,range,morale:82,ammo:100,fuel:100,supply:100,
    formation,parentHQ,
    // 让主系统明确知道这是动态生成单位；后续发生“同格冲突”时允许安全系统自动调整。
    autoGenerated:true,
    equipment:[{type:equipment,name:eqName(equipment),initial:qty,operational:qty,damaged:0,destroyed:0}],
    equipmentSummary:`${eqName(equipment)} ${qty}/${qty}`,
    modern:{c2:100,intelLevel:0,supply:100,ammo:100,fuel:100,parentHQ,exerciseSide:faction==="chinese"?"RED":"BLUE"}
  };
}

function maneuverCompanies(T,side,b,faction,slots,form,bnHQ){
  const p=`${side}_BN${b}`, a=[];
  const add=(suffix,name,type,eq,qty,atk,def,mov,slotIndex)=>{
    const x=slots[slotIndex];
    a.push(make(`${p}_${suffix}`,name,faction,type,"company",x.q,x.r,100,
      Math.round(atk*T.atk),Math.round(def*T.def),Math.max(4,Math.round(mov*T.mov)),type==="tank"?2:1,eq,qty,form,bnHQ));
  };
  if(T.maneuver==="heavy"){
    add("T1",`第${b}合成营坦克1连`,"tank",T.tank,14,12,10,5,0);
    add("T2",`第${b}合成营坦克2连`,"tank",T.tank,14,12,10,5,1);
    add("M1",`第${b}合成营装甲步兵1连`,"infantry",T.ifv,14,9,9,5,2);
    add("M2",`第${b}合成营装甲步兵2连`,"infantry",T.ifv,14,9,9,5,3);
  } else if(T.maneuver==="medium"){
    add("A1",`第${b}合成营轮式突击连`,"tank",T.tank,14,10,8,6,0);
    add("M1",`第${b}合成营轮式装步1连`,"infantry",T.ifv,14,9,8,6,1);
    add("M2",`第${b}合成营轮式装步2连`,"infantry",T.ifv,14,9,8,6,2);
    add("M3",`第${b}合成营轮式装步3连`,"infantry",T.ifv,14,9,8,6,3);
  } else {
    for(let i=0;i<4;i++) add(`L${i+1}`,`第${b}合成营高机动步兵${i+1}连`,"infantry",T.ifv,18,8,7,7,i);
  }
  const s=slots[4];
  a.push(make(`${p}_SUP`,`第${b}合成营支援保障连`,faction,"support","company",s.q,s.r,90,4,6,5,2,T.support,10,form,bnHQ));
  return a;
}

